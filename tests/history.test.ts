// Topological history: the input of topological naming in Moket.
import { beforeAll, describe, expect, it } from 'vitest';
import type { KindHistory, OcctKernel } from '../dist/index.js';
import { dot, loadKernel } from './kernel.js';
import { buildR1, buildR3, ok, rectLoop, XY } from './models.mjs';

let k: OcctKernel;
beforeAll(async () => {
  k = await loadKernel();
});

/** Result index for every input sub-shape that survives (modified to exactly one, or unchanged). */
function survivors(h: KindHistory, input = 0): Map<number, number[]> {
  const map = new Map<number, number[]>();
  for (const e of h.unchanged) if (e.input === input) map.set(e.from, [e.to]);
  for (const e of h.modified) if (e.input === input) map.set(e.from, [...(map.get(e.from) ?? []), ...e.to]);
  return map;
}

describe('makeProfileFace', () => {
  it('maps every segment to an edge index of the face', () => {
    const loop = rectLoop(0, 0, 40, 30);
    const profile = ok(k.makeProfileFace(XY, [loop]));
    expect(profile.segmentEdges).toHaveLength(1);
    expect([...profile.segmentEdges[0]].sort()).toEqual([0, 1, 2, 3]);

    const topo = ok(k.topology(profile.shape));
    profile.segmentEdges[0].forEach((edgeIndex, s) => {
      const seg = loop[s];
      const mid = [(seg.a[0] + seg.b[0]) / 2, (seg.a[1] + seg.b[1]) / 2, 0];
      topo.edges[edgeIndex].midpoint.forEach((v, i) => expect(v).toBeCloseTo(mid[i], 9));
    });
  });

  it('maps segments of hole loops too', () => {
    const profile = ok(
      k.makeProfileFace(XY, [
        rectLoop(0, 0, 50, 50),
        [{ kind: 'circle', center: [25, 25], radius: 5 }],
        rectLoop(5, 5, 5, 5),
      ]),
    );
    expect(profile.segmentEdges.map((l) => l.length)).toEqual([4, 1, 4]);
    expect(new Set(profile.segmentEdges.flat()).size).toBe(9);
    const props = ok(k.properties(profile.shape));
    expect(props.area).toBeCloseTo(2500 - 25 * Math.PI - 25, 9);
  });
});

describe('extrude history', () => {
  it('reports bottom, top and the side face generated by each sketch segment', () => {
    const loop = rectLoop(0, 0, 40, 30);
    const { profile, extrude } = buildR1(k);
    const topo = ok(k.topology(extrude.shape));
    const { sweep, history } = extrude;

    expect(sweep.bottom).toHaveLength(1);
    expect(sweep.top).toHaveLength(1);
    const bottom = topo.faces[sweep.bottom[0]];
    const top = topo.faces[sweep.top[0]];
    expect(bottom.normal[2]).toBeCloseTo(-1, 12);
    expect(top.normal[2]).toBeCloseTo(1, 12);
    expect(bottom.centroid[2]).toBeCloseTo(0, 12);
    expect(top.centroid[2]).toBeCloseTo(20, 12);

    // The profile face itself becomes the bottom (prism without copy).
    expect(history.faces.unchanged).toEqual([{ input: 0, from: 0, to: sweep.bottom[0] }]);

    const sideFaces = new Set<number>();
    profile.segmentEdges[0].forEach((edgeIndex, s) => {
      const gen = history.edges.generated.filter((g) => g.from === edgeIndex && g.kind === 'face');
      expect(gen).toHaveLength(1);
      expect(gen[0].to).toHaveLength(1);
      const face = gen[0].to[0];
      expect(sweep.sides.find((x) => x.edge === edgeIndex)?.faces).toEqual([face]);

      // The side face normal is perpendicular to the segment and points out
      // of the counter-clockwise profile.
      const seg = loop[s];
      const d = [seg.b[0] - seg.a[0], seg.b[1] - seg.a[1], 0];
      const n = topo.faces[face].normal;
      expect(dot(n, d)).toBeCloseTo(0, 12);
      const len = Math.hypot(d[0], d[1]);
      expect(dot(n, [d[1] / len, -d[0] / len, 0])).toBeCloseTo(1, 12);
      sideFaces.add(face);
    });
    expect(sideFaces.size).toBe(4);
    expect(new Set([...sideFaces, sweep.bottom[0], sweep.top[0]]).size).toBe(6);

    // Profile vertices generate the vertical edges.
    const vertical = history.vertices.generated.filter((g) => g.kind === 'edge');
    expect(vertical).toHaveLength(4);
    for (const g of vertical) {
      const e = topo.edges[g.to[0]];
      expect(e.length).toBeCloseTo(20, 12);
    }
  });
});

describe('fillet history', () => {
  it('maps the original faces to the result and lists the generated fillet faces', () => {
    const { r1, topEdges, fillet, shape } = buildR3(k);
    const before = ok(k.topology(r1.shape));
    const after = ok(k.topology(shape));
    expect(after.faces).toHaveLength(10);

    // Every original face survives as exactly one face, normal unchanged.
    const faces = survivors(fillet.history.faces);
    expect(faces.size).toBe(6);
    const kept = new Set<number>();
    for (const [from, to] of faces) {
      expect(to).toHaveLength(1);
      expect(dot(before.faces[from].normal, after.faces[to[0]].normal)).toBeCloseTo(1, 12);
      kept.add(to[0]);
    }
    expect(kept.size).toBe(6);

    // Each filleted edge generates one cylindrical face.
    const generated = fillet.history.edges.generated.filter((g) => g.kind === 'face');
    expect(generated.map((g) => g.from).sort()).toEqual([...topEdges].sort());
    const filletFaces = new Set<number>();
    for (const g of generated) {
      expect(g.to).toHaveLength(1);
      expect(after.faces[g.to[0]].surface).toBe('cylinder');
      filletFaces.add(g.to[0]);
    }
    expect(filletFaces.size).toBe(4);
    expect(new Set([...kept, ...filletFaces]).size).toBe(10);

    // Filleted edges are gone from the result.
    const survivingEdges = survivors(fillet.history.edges);
    for (const e of topEdges) expect(survivingEdges.has(e)).toBe(false);
  });
});

describe('boolean history', () => {
  it('cut: tracks plate faces, the hole face from the tool and deleted tool caps', () => {
    const plate = ok(k.makeBox(100, 60, 10)).shape;
    const tool = ok(k.makeCylinder([50, 30, -1], [0, 0, 1], 5, 12)).shape;
    const plateTopo = ok(k.topology(plate));
    const toolTopo = ok(k.topology(tool));
    const cut = ok(k.boolean('cut', plate, tool));
    const topo = ok(k.topology(cut.shape));
    expect(topo.faces).toHaveLength(7);

    const h = cut.history.faces;
    // Plate: side faces unchanged, top and bottom modified (they got a hole).
    const plateFaces = survivors(h, 0);
    expect(plateFaces.size).toBe(6);
    const modifiedPlate = h.modified.filter((e) => e.input === 0).map((e) => e.from);
    const capsOfPlate = plateTopo.faces.filter((f) => Math.abs(Math.abs(f.normal[2]) - 1) < 1e-12).map((f) => f.index);
    expect(modifiedPlate.sort()).toEqual(capsOfPlate.sort());

    // Tool: lateral face becomes the hole, caps are deleted.
    const lateral = toolTopo.faces.find((f) => f.surface === 'cylinder')!.index;
    const hole = h.modified.find((e) => e.input === 1 && e.from === lateral);
    expect(hole).toBeDefined();
    expect(hole!.to).toHaveLength(1);
    expect(topo.faces[hole!.to[0]].surface).toBe('cylinder');
    const deletedTool = h.deleted.filter((e) => e.input === 1).map((e) => e.from);
    const toolCaps = toolTopo.faces.filter((f) => f.surface === 'plane').map((f) => f.index);
    expect(deletedTool.sort()).toEqual(toolCaps.sort());

    // The circular hole edges are generated from tool faces intersecting the plate caps,
    // or modified from them; either way every result edge is accounted for.
    const accounted = new Set<number>();
    for (const kind of ['edges'] as const) {
      const eh = cut.history[kind];
      for (const e of eh.unchanged) accounted.add(e.to);
      for (const e of eh.modified) e.to.forEach((t) => accounted.add(t));
    }
    for (const kind of ['faces', 'edges'] as const) {
      for (const g of cut.history[kind].generated) if (g.kind === 'edge') g.to.forEach((t) => accounted.add(t));
    }
    expect(accounted.size).toBe(topo.edges.length);
  });

  it('fuse and common report both inputs', () => {
    const a = ok(k.makeBox(10, 10, 10)).shape;
    const b = ok(k.makeCylinder([10, 5, 0], [0, 0, 1], 3, 10)).shape;
    const fuse = ok(k.boolean('fuse', a, b));
    const inputs = new Set([...fuse.history.faces.modified, ...fuse.history.faces.unchanged].map((e) => e.input));
    expect(inputs).toEqual(new Set([0, 1]));
    const common = ok(k.boolean('common', a, b));
    const props = ok(k.properties(common.shape));
    expect(props.volume).toBeCloseTo((Math.PI * 9 * 10) / 2, 6);
  });
});
